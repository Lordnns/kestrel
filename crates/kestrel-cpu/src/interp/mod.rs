//! Portable ARM64 interpreter.
//!
//! Decoding follows the top-level A64 encoding groups (bits 28..25). Each
//! group lives in its own file. Handlers return `Ok(Flow)` to say how the PC
//! moves, or `Err(Exit)` to stop the run loop.
//!
//! Coverage today: integer data processing, branches, loads/stores
//! (including pairs, exclusives, SIMD registers and structures), system
//! registers, scalar half, single and double precision floating point, and
//! Advanced SIMD (NEON) with half precision, the dot product and the
//! AES, SHA-1 and SHA-256 crypto instructions. Anything else raises `Exit::Undefined` (or
//! `Exit::Unsupported`) so the gap is visible instead of silently wrong.

pub(crate) mod bits;
mod branch;
mod dp_imm;
mod dp_reg;
mod fp;
mod ldst;
mod neon;
