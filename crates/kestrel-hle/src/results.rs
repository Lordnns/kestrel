#[cfg(test)]
mod tests {
    use super::describe;

    #[test]
    fn results_read_as_switchbrew_writes_them() {
        assert_eq!(describe(0x202), "2002-0001 (Fs)");
        // libnx's MAKERESULT(Module_Libnx, LibnxError_InitFail_FS).
        assert_eq!(describe(345 | 33 << 9), "2345-0033 (Libnx: InitFail_FS)");
        assert_eq!(describe(345 | 999 << 9), "2345-0999 (Libnx)");
        assert_eq!(describe(0x1ff), "2511-0000");
    }
}
