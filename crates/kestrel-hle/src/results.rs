//! Result codes as people read them. Switchbrew's "Error codes" page
//! writes a result as 2000 plus its module, a dash and its description
//! ("2002-0001"), and names the modules; this table is that list. libnx's
//! own modules (345 to 349) and its error descriptions are from libnx's
//! `nx/include/switch/result.h`. Generated from those two sources.

/// `result` as "2345-0033 (Libnx: InitFail_FS)", or with the module
/// name alone when the description has no name here.
pub fn describe(result: u32) -> String {
    let (module, description) = (result & 0x1ff, result >> 9 & 0x1fff);
    let code = format!("{:04}-{:04}", 2000 + module, description);
    let Ok(i) = MODULES.binary_search_by_key(&module, |&(m, _)| m) else {
        return code;
    };
    let name = MODULES[i].1;
    match LIBNX_ERRORS.get((description as usize).wrapping_sub(1)) {
        Some(error) if module == 345 => format!("{code} ({name}: {error})"),
        _ => format!("{code} ({name})"),
    }
}

